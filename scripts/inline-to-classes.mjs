#!/usr/bin/env node
// INLINE FONT SIZES AND COLOURS → CLASSES (R-013), with a proof for every single change.
//
// WHY. An inline `style="font-size:11px;color:var(--text3)"` cannot be re-themed, re-scaled for a phone or
// re-laid-out by any stylesheet rule — public/mobile.css says so in its own words. There were ~1,600 of them. This
// turns the TYPE declarations (font-size in px, and colour when it is a theme variable) into utility classes
// (`.fs-11`, `.c-text3`, defined once in public/ui.css), and leaves every other declaration where it is.
//
// WHY A PROOF. A class is not the same as an inline style: an inline declaration beats every ordinary rule, a class
// does not, so `.dt td{font-size:12px}` or a `[data-theme=dark] …{color:…}` that used to lose to the inline value
// would start to WIN, and the screen would change. So nothing is converted on trust. For every candidate tag the
// tool builds the tag both ways, mounts both in the REAL app (real stylesheets, real shell) inside the surroundings
// real screens use — page card, table cell, popup, drawer, a lead row, the sidebar … — at desktop AND phone width,
// in the light, dark and default palettes, and compares the computed font size and colour. A candidate that is not
// IDENTICAL everywhere stays inline and is reported. The page cannot change by construction; what remains inline is
// exactly the list of places where a stylesheet rule is fighting an inline value (worth a look on its own).
//
// WHAT IT NEVER TOUCHES: a tag split by string concatenation, a style with a dynamic part, `!important`,
// em/rem/% sizes, hard-coded colours (#fff …: a colour with no theme variable is a design decision, not a tidy-up),
// font-weight (public/js/10a-window-dock.js selects on it), and every non-type declaration.
//
// Usage:  node scripts/inline-to-classes.mjs            dry run: prove, report, change nothing
//         node scripts/inline-to-classes.mjs --apply    write the passing conversions + the utility CSS
//         --report=path.json  keep the full report      --min=N  smallest number of uses that earns a class (default 2)
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const { chromium } = require(path.join(ROOT, 'node_modules/playwright-core'));
const { enterApp, waitForLogin } = await import(path.join(ROOT, 'test/helpers/enter-app.mjs'));

const APPLY = process.argv.includes('--apply');
const MIN = +(process.argv.find(a => a.startsWith('--min=')) || '--min=2').split('=')[1];
const REPORT = (process.argv.find(a => a.startsWith('--report=')) || '').split('=')[1] || '';
const JS_DIR = path.join(ROOT, 'public/js');
const CSS = path.join(ROOT, 'public/ui.css');
const BEGIN = '/* R-013 UTILITIES BEGIN — generated by scripts/inline-to-classes.mjs; do not edit by hand */';
const END = '/* R-013 UTILITIES END */';

// A complete, static opening tag: no string boundary (') and no escaped quote inside it.
const TAG = /<([a-zA-Z][a-zA-Z0-9]*)((?:[^<>'"\\]|"[^"\\]*")*)>/g;
const FS = /^font-size:\s*([0-9]+(?:\.[0-9]+)?)px$/;
const COL = /^color:\s*var\(--([a-z0-9-]+)\)$/;
const cls = {
  fs: v => 'fs-' + v.replace('.', '_'),
  c: n => 'c-' + n,
};

// ── 1. find the candidates ────────────────────────────────────────────────────────────────────────────────────────
const files = fs.readdirSync(JS_DIR).filter(f => f.endsWith('.js')).sort();
const src = {}; const cands = []; const useFs = {}; const useCol = {};
for (const f of files) {
  const s = fs.readFileSync(path.join(JS_DIR, f), 'utf8'); src[f] = s;
  TAG.lastIndex = 0; let m;
  while ((m = TAG.exec(s))) {
    const attrs = m[2]; const sm = /\sstyle="([^"]*)"/.exec(attrs);
    if (!sm) continue;
    const decls = sm[1].split(';').map(d => d.trim()).filter(Boolean);
    if (decls.some(d => /!important|\{|\}/.test(d))) continue;
    const props = decls.map(d => d.split(':')[0].trim().toLowerCase());
    if (new Set(props).size !== props.length) continue;            // a repeated property: leave it alone
    const fsd = decls.find(d => FS.test(d)), cod = decls.find(d => COL.test(d));
    if (!fsd && !cod) continue;
    cands.push({ f, start: m.index, end: m.index + m[0].length, tag: m[1].toLowerCase(), attrs, decls, fsd, cod });
    if (fsd) { const v = FS.exec(fsd)[1]; useFs[v] = (useFs[v] || 0) + 1; }
    if (cod) { const n = COL.exec(cod)[1]; useCol[n] = (useCol[n] || 0) + 1; }
  }
}
const okFs = new Set(Object.keys(useFs).filter(v => useFs[v] >= MIN));
const okCol = new Set(Object.keys(useCol).filter(n => useCol[n] >= MIN));

// ── 2. build each candidate's converted form ─────────────────────────────────────────────────────────────────────
function convert(c) {
  const add = []; const keep = [];
  for (const d of c.decls) {
    if (d === c.fsd && okFs.has(FS.exec(d)[1])) add.push(cls.fs(FS.exec(d)[1]));
    else if (d === c.cod && okCol.has(COL.exec(d)[1])) add.push(cls.c(COL.exec(d)[1]));
    else keep.push(d);
  }
  if (!add.length) return null;
  let attrs = c.attrs.replace(/\sstyle="[^"]*"/, keep.length ? ' style="' + keep.join(';') + '"' : '');
  if (/\sclass="/.test(attrs)) attrs = attrs.replace(/(\sclass=")([^"]*)(")/, (_, a, v, z) => a + (v ? v + ' ' : '') + add.join(' ') + z);
  else attrs = attrs.replace(/(\sstyle="|$)/, m0 => ' class="' + add.join(' ') + '"' + m0);
  return { attrs, add };
}
for (const c of cands) c.conv = convert(c);
const todo = cands.filter(c => c.conv);
const keyOf = c => c.tag + '|' + c.attrs;
const unique = new Map(); for (const c of todo) if (!unique.has(keyOf(c))) unique.set(keyOf(c), c);

// ── 3. the utility CSS (written BEFORE probing so the converted form really resolves) ────────────────────────────
const usedFs = new Set(), usedCol = new Set();
for (const c of todo) for (const a of c.conv.add) { if (a.startsWith('fs-')) usedFs.add(a.slice(3).replace('_', '.')); else usedCol.add(a.slice(2)); }
const css =
  BEGIN + '\n' +
  '/* Type and colour utilities (R-013). Each is EXACTLY a value that used to be written inline, so nothing changed on\n' +
  '   screen. One home, so a phone scale or a palette can reach them. Plain single-class rules on purpose: unlike an\n' +
  '   inline value they can be overridden by a theme or phone rule, which is the point. */\n' +
  [...usedFs].sort((a, b) => a - b).map(v => '.' + cls.fs(v) + '{font-size:' + v + 'px}').join('\n') + '\n' +
  [...usedCol].sort().map(n => '.' + cls.c(n) + '{color:var(--' + n + ')}').join('\n') + '\n' + END + '\n';
const ORIG_UI = fs.readFileSync(CSS, 'utf8');
let ui = ORIG_UI;
const hadBlock = ui.includes(BEGIN);
if (hadBlock) ui = ui.slice(0, ui.indexOf(BEGIN)) + css + ui.slice(ui.indexOf(END) + END.length).replace(/^\n/, '');
else ui = ui.replace(/\n*$/, '\n\n') + css;
fs.writeFileSync(CSS, ui);       // restored below on a dry run

// ── 4. prove it in the real app ──────────────────────────────────────────────────────────────────────────────────
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const server = http.createServer((req, res) => {
  let p = decodeURIComponent(req.url.split('?')[0]); if (p === '/') p = '/index.html';
  fs.readFile(path.join(ROOT, 'public', p), (e, d) => { if (e) { res.writeHead(404); return res.end('nf'); } res.writeHead(200, { 'Content-Type': MIME[path.extname(p)] || 'application/octet-stream' }); res.end(d); });
});
const PORT = await new Promise(r => server.listen(0, '127.0.0.1', () => r(server.address().port)));
const BASE = `http://127.0.0.1:${PORT}`;
function findChromium() {
  if (process.env.PLAYWRIGHT_CHROMIUM) return process.env.PLAYWRIGHT_CHROMIUM;
  const b = process.env.PLAYWRIGHT_BROWSERS_PATH; if (b && fs.existsSync(path.join(b, 'chromium'))) return path.join(b, 'chromium');
  return 'chromium';
}
// The surroundings real screens put these tags in. `@` is where the tag goes; `into` is the shell region.
const VOID = new Set(['input', 'img', 'br', 'hr', 'col', 'meta', 'link', 'source', 'area', 'base', 'embed', 'track', 'wbr']);
const CONTEXTS = [
  { name: 'page card',     into: '#content', html: '<div class="page"><div class="card" style="padding:16px">@</div></div>' },
  { name: 'page (bare)',   into: '#content', html: '<div class="page">@</div>' },
  { name: 'dt-wrap',       into: '#content', html: '<div class="page"><div class="dt-wrap">@</div></div>' },
  { name: 'tbl-wrap',      into: '#content', html: '<div class="page"><div class="tbl-wrap">@</div></div>' },
  { name: 'card > table',  into: '#content', html: '<div class="page"><div class="card" style="padding:0">@</div></div>' },
  { name: 'modal table',   into: '#layer',   html: '<div class="overlay"><div class="modal"><div class="mbody">@</div></div></div>' },
  { name: 'lead row open', into: '#content', html: '<div class="page"><table class="dt"><tbody><tr class="row-exp"><td><div class="lx-contact">@</div></td></tr></tbody></table></div>' },
  { name: 'form group',    into: '#content', html: '<div class="page"><div class="card"><div class="fgrp">@</div></div></div>' },
  { name: 'tabs',          into: '#content', html: '<div class="page"><div class="pgtabs">@</div></div>' },
  { name: 'modal',         into: '#layer',   html: '<div class="overlay"><div class="modal"><div class="mbody">@</div></div></div>' },
  { name: 'modal form',    into: '#layer',   html: '<div class="overlay"><div class="modal"><div class="mbody"><div class="fgrp">@</div></div></div></div>' },
  { name: 'drawer',        into: '#layer',   html: '<div class="dwr-scrim"><div class="dwr"><div class="dwr-pane dwr-left"><div class="dwr-fields">@</div></div></div></div>' },
  { name: 'sidebar',       into: '#sidebar', html: '<div class="sb-nav">@</div>' },
];
function wrap(tag, inner, ctx) {                       // table-ish tags need their own parents to exist at all
  if (tag === 'td' || tag === 'th') return ctx.table ? '<tr>' + inner + '</tr>' : '<table class="dt"><tbody><tr>' + inner + '</tr></tbody></table>';
  if (tag === 'tr') return ctx.table ? inner : '<table class="dt"><tbody>' + inner + '</tbody></table>';
  if (tag === 'thead' || tag === 'tbody' || tag === 'tfoot') return ctx.table ? inner : '<table class="dt">' + inner + '</table>';
  if (tag === 'li') return '<ul>' + inner + '</ul>';
  if (tag === 'option') return '<select>' + inner + '</select>';
  if (ctx.table) return '<tr><td>' + inner + '</td></tr>';
  return inner;
}
const items = [...unique.values()].map((c, i) => ({
  i, tag: c.tag,
  a: '<' + c.tag + c.attrs + ' data-pk="' + i + 'a">' + (VOID.has(c.tag) ? '' : 'x</' + c.tag + '>'),
  b: '<' + c.tag + c.conv.attrs + ' data-pk="' + i + 'b">' + (VOID.has(c.tag) ? '' : 'x</' + c.tag + '>'),
}));

const browser = await chromium.launch({ executablePath: findChromium(), headless: true, args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage'] });
const failed = new Map();      // item index -> first difference
let probes = 0;
try {
  const ctxB = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await ctxB.route('**', r => r.request().url().startsWith(BASE) ? r.continue() : r.abort());
  const page = await ctxB.newPage();
  await page.goto(BASE + '/'); await waitForLogin(page); await enterApp(page, 'admin');
  for (const vp of [{ width: 1280, height: 900 }, { width: 390, height: 800 }]) {
    await page.setViewportSize(vp); await page.waitForTimeout(150);
    for (const theme of [null, 'light', 'dark']) {
      await page.evaluate(t => { if (t) document.documentElement.setAttribute('data-theme', t); else document.documentElement.removeAttribute('data-theme'); }, theme);
      for (const ctx of CONTEXTS) {
        const diffs = await page.evaluate(({ items, ctx, CHUNK }) => {
          const host = document.querySelector(ctx.into) || document.body;
          const out = [];
          const props = ['fontSize', 'color', 'lineHeight'];
          for (let s = 0; s < items.length; s += CHUNK) {
            const part = items.slice(s, s + CHUNK);
            // Table-ish tags bring their own table, in every shape real screens use: classed or bare, in <thead> or
            // <tbody> (a `thead th` rule never reaches a th placed in a tbody — the first version of this probe did
            // exactly that and missed 176 headers that grew from 11px to 12px).
            const VAR = (tag) => {
              if (tag !== 'td' && tag !== 'th' && tag !== 'tr' && tag !== 'thead' && tag !== 'tbody') return [x => x];
              const out = [];
              for (const tc of ['dt', '', 'dt tbl']) for (const sec of ['tbody', 'thead']) {
                const t0 = '<table' + (tc ? ' class="' + tc + '"' : '') + '>';
                if (tag === 'td' || tag === 'th') out.push(x => t0 + '<' + sec + '><tr>' + x + '</tr></' + sec + '></table>');
                else if (tag === 'tr') out.push(x => t0 + '<' + sec + '>' + x + '</' + sec + '></table>');
                else out.push(x => t0 + x + '</table>');
              }
              return out;
            };
            const wrapOne = (tag, inner) => tag === 'li' ? '<ul>' + inner + '</ul>' : tag === 'option' ? '<select>' + inner + '</select>' : inner;
            const maxV = Math.max(...part.map(it => VAR(it.tag).length));
            for (let v = 0; v < maxV; v++) {
              const box = document.createElement('div'); box.setAttribute('data-r013', '1');
              const sub = part.filter(it => v < VAR(it.tag).length);
              box.innerHTML = ctx.html.replace('@', sub.map(it => { const w = VAR(it.tag)[v]; return w(wrapOne(it.tag, it.a)) + w(wrapOne(it.tag, it.b)); }).join(''));
              host.appendChild(box);
              for (const it of sub) {
                const ea = box.querySelector('[data-pk="' + it.i + 'a"]'), eb = box.querySelector('[data-pk="' + it.i + 'b"]');
                if (!ea || !eb) { out.push([it.i, 'not drawn']); continue; }
                const ca = getComputedStyle(ea), cb = getComputedStyle(eb);
                for (const p of props) if (ca[p] !== cb[p]) { out.push([it.i, p + ': ' + ca[p] + ' → ' + cb[p] + ' (variant ' + v + ')']); break; }
              }
              box.remove();
            }
          }
          return out;
        }, { items: items.map(({ i, tag, a, b }) => ({ i, tag, a, b })), ctx: { into: ctx.into, html: ctx.html }, CHUNK: 400 });
        probes += items.length;
        for (const [i, why] of diffs) if (!failed.has(i)) failed.set(i, { why, where: ctx.name + ' · ' + vp.width + 'px · ' + (theme || 'default') });
      }
    }
  }
} finally { await browser.close(); server.close(); }

// ── 5. apply what is proven ─────────────────────────────────────────────────────────────────────────────────────
const failKeys = new Set([...failed.keys()].map(i => keyOf({ tag: items[i].tag, attrs: [...unique.values()][i].attrs })));
const passing = todo.filter(c => !failKeys.has(keyOf(c)));
const skipped = todo.filter(c => failKeys.has(keyOf(c)));
const sizesBefore = cands.filter(c => c.fsd).length;
if (APPLY) {
  const byFile = {};
  for (const c of passing) (byFile[c.f] = byFile[c.f] || []).push(c);
  for (const f of Object.keys(byFile)) {
    let s = src[f];
    for (const c of byFile[f].sort((a, b) => b.start - a.start)) s = s.slice(0, c.start) + '<' + c.tag + c.conv.attrs + '>' + s.slice(c.end);
    fs.writeFileSync(path.join(JS_DIR, f), s);
  }
} else {
  // a dry run leaves the stylesheet exactly as it found it
  fs.writeFileSync(CSS, ORIG_UI);
}
const why = {}; for (const c of skipped) { const w = failed.get([...unique.keys()].indexOf(keyOf(c))); const k = (w && w.why.split(':')[0]) + ' @ ' + (w && w.where.split(' · ')[0]); why[k] = (why[k] || 0) + 1; }
const summary = {
  inlineStyleAttributes: 'see scan', candidatesWithTypeDecl: cands.length, convertible: todo.length, proven: passing.length, keptInline: skipped.length,
  uniqueShapesProbed: items.length, probesRun: probes, fontSizesBefore: sizesBefore,
  classes: { fontSize: [...usedFs].length, colour: [...usedCol].length },
  keptInlineBecause: Object.fromEntries(Object.entries(why).sort((a, b) => b[1] - a[1]).slice(0, 15)),
  applied: APPLY,
};
console.log(JSON.stringify(summary, null, 2));
if (REPORT) fs.writeFileSync(REPORT, JSON.stringify({ summary, skipped: skipped.map(c => ({ f: c.f, tag: c.tag, attrs: c.attrs.slice(0, 200), conflict: failed.get([...unique.keys()].indexOf(keyOf(c))) })) }, null, 1));
